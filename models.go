package moblin

import "time"

// --- Messages to Streamer ---

// ResultPayload maps to the Swift RemoteControlResult enum.
// Because Swift Codable serializes enums without raw values as keyed objects,
// only one of these fields will be non-nil.
type ResultPayload struct {
	Ok                *struct{} `json:"ok,omitempty"`                // Operation succeeded
	WrongPassword     *struct{} `json:"wrongPassword,omitempty"`     // Authentication failed
	UnknownRequest    *struct{} `json:"unknownRequest,omitempty"`    // Command not recognized by Moblin
	NotIdentified     *struct{} `json:"notIdentified,omitempty"`     // Command sent before authentication
	AlreadyIdentified *struct{} `json:"alreadyIdentified,omitempty"` // Duplicate identify payload
	Error             *struct{} `json:"error,omitempty"`             // General operational failure
}

// MessageToStreamer is the envelope for all data sent from the Assistant to the Moblin app.
type MessageToStreamer struct {
	Hello      *HelloData      `json:"hello,omitempty"`      // Initial handshake from server containing challenge
	Identified *IdentifiedData `json:"identified,omitempty"` // Server's response to Moblin's identify payload
	Request    *RequestPayload `json:"request,omitempty"`    // RPC command (e.g., start recording, zoom)
	Pong       *struct{}       `json:"pong,omitempty"`       // Keepalive response
}

// HelloData initiates the double-SHA256 authentication flow.
type HelloData struct {
	ApiVersion     string         `json:"apiVersion"`     // Currently "0.1"
	Authentication Authentication `json:"authentication"` // Contains the generated challenge/salt
}

type Authentication struct {
	Challenge string `json:"challenge"` // Random string generated by Assistant
	Salt      string `json:"salt"`      // Random string generated by Assistant
}

// IdentifiedData confirms or denies the Moblin app's connection attempt.
type IdentifiedData struct {
	Result ResultPayload `json:"result"`
}

// RequestPayload wraps a specific command with an incrementing ID to track synchronous responses.
type RequestPayload struct {
	ID   uint64  `json:"id"`
	Data Request `json:"data"`
}

// --- Request Core ---

// Request models all cases of the Swift RemoteControlRequest enum.
// These are commands the Assistant sends to control the Moblin stream.
type Request struct {
	GetStatus                         *struct{}               `json:"getStatus,omitempty"`                         // Polls for current battery, thermal, and UI element status
	GetSettings                       *struct{}               `json:"getSettings,omitempty"`                       // Fetches configured scenes, mics, and bitrate presets
	SetRecord                         *BoolReq                `json:"setRecord,omitempty"`                         // Toggles local device recording
	SetStream                         *BoolReq                `json:"setStream,omitempty"`                         // Toggles RTMP/SRT streaming
	SetZoom                           *FloatReq               `json:"setZoom,omitempty"`                           // Sets raw camera zoom level (e.g., 1.0, 2.0)
	SetZoomPreset                     *UUIDReq                `json:"setZoomPreset,omitempty"`                     // Switches to a predefined zoom preset ID
	SetMute                           *BoolReq                `json:"setMute,omitempty"`                           // Toggles microphone mute
	SetTorch                          *BoolReq                `json:"setTorch,omitempty"`                          // Toggles the device flashlight
	SetDebugLogging                   *BoolReq                `json:"setDebugLogging,omitempty"`                   // Toggles verbose internal logging
	SetScene                          *UUIDReq                `json:"setScene,omitempty"`                          // Switches to a specific Scene ID
	SetAutoSceneSwitcher              *UUIDReq                `json:"setAutoSceneSwitcher,omitempty"`              // Enables/disables automatic scene switching logic
	SetBitratePreset                  *UUIDReq                `json:"setBitratePreset,omitempty"`                  // Switches to a specific Bitrate Preset ID
	SetMic                            *StringIDReq            `json:"setMic,omitempty"`                            // Switches the active microphone hardware
	SetSrtConnectionPriority          *SetSrtPriorityReq      `json:"setSrtConnectionPriority,omitempty"`          // Modifies cellular/WiFi bonding priority for SRT connections
	SetSrtConnectionPrioritiesEnabled *EnabledReq             `json:"setSrtConnectionPrioritiesEnabled,omitempty"` // Toggles SRT connection bonding logic
	ReloadBrowserWidgets              *struct{}               `json:"reloadBrowserWidgets,omitempty"`              // Forces a refresh of all web overlays
	TwitchEventSubNotification        *MessageReq             `json:"twitchEventSubNotification,omitempty"`        // Proxies a Twitch EventSub notification to the streamer
	StartPreview                      *struct{}               `json:"startPreview,omitempty"`                      // Commands Moblin to start sending JPEG preview frames
	StopPreview                       *struct{}               `json:"stopPreview,omitempty"`                       // Commands Moblin to stop sending preview frames
	ChatMessages                      *ChatMessagesReq        `json:"chatMessages,omitempty"`                      // Proxies chat messages (e.g., from Twitch/YouTube) into the app
	SetRemoteSceneSettings            *RemoteSceneSettingsReq `json:"setRemoteSceneSettings,omitempty"`            // Overrides remote scene configurations
	SetRemoteSceneData                *RemoteSceneDataReq     `json:"setRemoteSceneData,omitempty"`                // Pushes real-time IRL telemetry (speed, altitude, HR) to widgets
	InstantReplay                     *struct{}               `json:"instantReplay,omitempty"`                     // Triggers an instant replay buffer
	SaveReplay                        *struct{}               `json:"saveReplay,omitempty"`                        // Saves the current replay buffer to disk
	StartStatus                       *StartStatusReq         `json:"startStatus,omitempty"`                       // Initiates a continuous stream of `Event.Status` payloads at the given interval
	StopStatus                        *struct{}               `json:"stopStatus,omitempty"`                        // Stops the continuous status stream
	GetScoreboardSports               *struct{}               `json:"getScoreboardSports,omitempty"`               // Fetches available sports logic for the scoreboard widget
	SetScoreboardSport                *SportIDReq             `json:"setScoreboardSport,omitempty"`                // Sets the active sport logic
	UpdateScoreboard                  *UpdateScoreboardReq    `json:"updateScoreboard,omitempty"`                  // Updates the teams, scores, and clocks on the scoreboard overlay
	ToggleScoreboardClock             *struct{}               `json:"toggleScoreboardClock,omitempty"`             // Pauses/resumes the scoreboard timer
	SetScoreboardDuration             *MinutesReq             `json:"setScoreboardDuration,omitempty"`             // Sets the timer duration
	SetScoreboardClock                *TimeReq                `json:"setScoreboardClock,omitempty"`                // Hard-sets the clock string (e.g., "12:00")
	Whip                              *WhipReq                `json:"whip,omitempty"`                              // WebRTC HTTP Ingestion Protocol signaling
	SetFilter                         *SetFilterReq           `json:"setFilter,omitempty"`                         // Enables/disables specific video filters (e.g., Pixellate, BlurFaces)
}

// --- Request Wrappers ---

type BoolReq struct {
	On bool `json:"on"`
}
type FloatReq struct {
	X float32 `json:"x"`
}
type UUIDReq struct {
	ID string `json:"id"` // Moblin UUIDs serialize to standard uppercase dashed strings
}
type StringIDReq struct {
	ID string `json:"id"`
}
type MessageReq struct {
	Message string `json:"message"`
}
type EnabledReq struct {
	Enabled bool `json:"enabled"`
}
type SportIDReq struct {
	SportID string `json:"sportId"` // e.g., "football"
}
type MinutesReq struct {
	Minutes int `json:"minutes"`
}
type TimeReq struct {
	Time string `json:"time"`
}

type SetSrtPriorityReq struct {
	ID       string `json:"id"`
	Priority int    `json:"priority"` // Lower number = higher priority for bonding
	Enabled  bool   `json:"enabled"`
}

type ChatMessagesReq struct {
	History  bool          `json:"history"` // True if injecting backlog history, false for real-time
	Messages []ChatMessage `json:"messages"`
}

type RemoteSceneSettingsReq struct {
	Data RemoteSceneSettings `json:"data"`
}
type RemoteSceneDataReq struct {
	Data RemoteSceneData `json:"data"`
}
type UpdateScoreboardReq struct {
	Config ScoreboardMatchConfig `json:"config"`
}

type StartStatusFilter struct {
	TopRight bool `json:"topRight"` // True explicitly enables TopRight UI telemetry
}
type StartStatusReq struct {
	Interval int               `json:"interval"` // Frequency in seconds to push Status payload
	Filter   StartStatusFilter `json:"filter"`
}

type WhipReq struct {
	URL     string       `json:"url"`
	Method  string       `json:"method"`
	Headers []HttpHeader `json:"headers"`
	Body    []byte       `json:"body"`
}

type SetFilterReq struct {
	Filter string `json:"filter"` // Maps to RemoteControlFilter enum (e.g., "pixellate", "blurFaces")
	On     bool   `json:"on"`
}

// --- Response Wrappers ---

// ResponseData holds the synchronous return payloads triggered by Request commands.
type ResponseData struct {
	GetStatus           *StatusPayload   `json:"getStatus,omitempty"`
	GetSettings         *SettingsPayload `json:"getSettings,omitempty"`
	GetScoreboardSports *SportsPayload   `json:"getScoreboardSports,omitempty"`
	Whip                *WhipPayload     `json:"whip,omitempty"`
}

type SettingsPayload struct {
	Data Settings `json:"data"`
}
type SportsPayload struct {
	Names []string `json:"names"`
}
type WhipPayload struct {
	Status  int          `json:"status"`
	Headers []HttpHeader `json:"headers"`
	Body    []byte       `json:"body"`
}

// --- Core Models ---

// Settings outlines the streaming configuration currently loaded into Moblin.
type Settings struct {
	Scenes             []Scene             `json:"scenes"` // Available scene templates
	AutoSceneSwitchers []AutoSceneSwitcher `json:"autoSceneSwitchers,omitempty"`
	BitratePresets     []BitratePreset     `json:"bitratePresets"` // Target streaming bitrates
	Mics               []Mic               `json:"mics"`           // Available microphone hardware routes
	Srt                SrtSettings         `json:"srt"`            // Secure Reliable Transport bonding config
}

type Scene struct {
	ID   string `json:"id"`
	Name string `json:"name"`
}

type AutoSceneSwitcher struct {
	ID   string `json:"id"`
	Name string `json:"name"`
}

type BitratePreset struct {
	ID      string `json:"id"`
	Bitrate uint32 `json:"bitrate"` // Value in bps (e.g., 5000000 for 5Mbps)
}

type Mic struct {
	ID   string `json:"id"`   // Internal iOS route ID
	Name string `json:"name"` // Human-readable name (e.g., "Back Wide dual")
}

type SrtSettings struct {
	ConnectionPrioritiesEnabled bool                    `json:"connectionPrioritiesEnabled"`
	ConnectionPriorities        []SrtConnectionPriority `json:"connectionPriorities"`
}

type SrtConnectionPriority struct {
	ID       string `json:"id"`
	Name     string `json:"name"`     // Interface name (e.g., "Cellular", "WiFi")
	Priority int    `json:"priority"` // Ordering for SRTLA bonding
	Enabled  bool   `json:"enabled"`
}

type HttpHeader struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

// ChatMessage represents a single proxied chat payload intended for Moblin's chat widget.
type ChatMessage struct {
	ID           int           `json:"id"`
	Platform     string        `json:"platform"` // e.g., "twitch", "youtube"
	MessageID    *string       `json:"messageId,omitempty"`
	DisplayName  *string       `json:"displayName,omitempty"`
	User         *string       `json:"user,omitempty"`
	UserID       *string       `json:"userId,omitempty"`
	UserColor    interface{}   `json:"userColor,omitempty"`
	UserBadges   []string      `json:"userBadges"` // URLs pointing to badge icon images
	Segments     []interface{} `json:"segments"`   // Sliced array of text/emote blocks
	Timestamp    string        `json:"timestamp"`  // String formatted time
	IsAction     bool          `json:"isAction"`
	IsModerator  bool          `json:"isModerator"`
	IsSubscriber bool          `json:"isSubscriber"`
	IsOwner      bool          `json:"isOwner"`
	Bits         *string       `json:"bits,omitempty"`
}

